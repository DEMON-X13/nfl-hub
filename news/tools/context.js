const normName = s => String(s || '').toLowerCase().replace(/[.'’,]/g, '').replace(/-/g, ' ')
  .replace(/\b(jr|sr|ii|iii|iv|v)\b/g, '').replace(/\s+/g, ' ').trim();
const lc = s => String(s || '').trim().toLowerCase();
const CHART_DAYS = 10;
