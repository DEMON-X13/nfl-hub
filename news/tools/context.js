function ranks(root, out) {
  const stateFile = path.resolve(root, '..', 'betting', 'state.json');
  if (!fs.existsSync(stateFile)) { console.log('ranks2026.js kept: ../betting/state.json not found'); return; }
  const st = JSON.parse(fs.readFileSync(stateFile, 'utf8'));
  const teams = Object.entries(st.teams || {}).map(([t, v]) => [ab(t), v.elo]).filter(([, e]) => isFinite(e)).sort((a, b) => b[1] - a[1]);
  if (teams.length < 32) { console.log(`ranks2026.js kept: only ${teams.length} teams on the board`); return; }
  const R = {}; teams.forEach(([t, e], i) => { R[t] = { rank: i + 1, elo: Math.round(e) }; });
  const asof = st.published ? new Date(st.published).toISOString().slice(0, 10) : '';
  writeData(path.join(out, 'ranks2026.js'), 'RANKS26', R, `const RANKS26_ASOF = ${JSON.stringify(asof)};\n`);
  console.log(`ranks2026.js: ${teams.length} teams, #1 ${teams[0][0]}, as of ${asof}`);
}

