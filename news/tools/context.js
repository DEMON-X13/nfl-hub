const isOL = p => ['T', 'G', 'C', 'OL', 'OT', 'OG'].includes(p), isFront = p => ['DE', 'DT', 'NT', 'DL', 'LB', 'OLB', 'ILB', 'MLB', 'EDGE'].includes(p);
const isDB = p => ['CB', 'S', 'FS', 'SS', 'DB', 'SAF'].includes(p);
